/* -------------------------------------------------------
   🚀 検索文字列の正規化
   ・前後の空白を除去
   ・連続する空白を1つに圧縮
   ・全角スペース／全角英数字を半角に変換
   ・小文字化（ILIKE と組み合わせて大文字小文字を無視）
------------------------------------------------------- */
export function normalizeText(str) {
  if (!str) return "";

  return str
    .normalize("NFKC")          // 全角英数字・記号 → 半角に統一
    .replace(/\s+/g, " ")       // 連続する空白を1つに圧縮（全角スペースもNFKCで半角化済み）
    .trim()
    .toLowerCase();
}
